import {test,expect} from './fixture';
test('path tracing respects active relationship filters and keeps controls selected',async({page})=>{
  await page.goto('/upload');
  await page.getByRole('button',{name:'Data file',exact:true}).click();
  await page.getByLabel('Choose evidence file').setInputFiles({name:'paths.csv',mimeType:'text/csv',buffer:Buffer.from('src,dst,rel\nA,B,CALLED\nB,C,PAID\nA,C,KNOWS')});
  await page.getByLabel('I’ve reviewed the mapping and cleaned records.').check();
  await page.getByRole('button',{name:'Build network',exact:true}).click();
  await expect(page).toHaveURL(/overview/);
  await page.goto('/network');
  await page.getByRole('button',{name:'Filters',exact:true}).click();
  await page.getByRole('button',{name:'Associate of',exact:true}).click();
  await page.getByLabel('Community',{exact:true}).selectOption('0');
  await page.getByRole('button',{name:'Find a path',exact:true}).click();
  await page.getByLabel('Path start entity',{exact:true}).selectOption('A');
  await page.getByLabel('Path end entity',{exact:true}).selectOption('C');
  const pending=page.waitForResponse(r=>r.url().endsWith('/workspace/paths'));
  await page.getByRole('button',{name:'Trace path',exact:true}).click();
  expect((await(await pending).json()).paths).toEqual([['A','B','C']]);
  await expect(page.getByRole('button',{name:'Associate of',exact:true})).not.toHaveClass(/selected/);
  await expect(page.getByLabel('Community',{exact:true})).toHaveValue('0');
  await page.getByRole('button',{name:'Financial transfer',exact:true}).click();
  await page.getByRole('button',{name:'Trace path',exact:true}).click();
  await expect(page.getByText(/No path within 3 hops under these filters/)).toBeVisible();
});
